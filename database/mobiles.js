/* =========================================================
   DATABASE FUNCTIONS
   ========================================================= */

const MobileDatabase = {

    getAll() {
        return TECHFIX_MOBILES;
    },


    getById(id) {
        return TECHFIX_MOBILES.find(
            mobile => mobile.id === id
        ) || null;
    },


    getByBrand(brand) {
        return TECHFIX_MOBILES.filter(
            mobile =>
                mobile.brand.toLowerCase() ===
                brand.toLowerCase()
        );
    },


    search(query) {

        const term = query
            .trim()
            .toLowerCase();

        if (!term) {
            return [];
        }

        return TECHFIX_MOBILES.filter(mobile => {

            const searchableText = [
                mobile.brand,
                mobile.model,
                mobile.modelNumber,
                mobile.platform,
                mobile.chipset,
                mobile.android,
                mobile.bootType
            ]
                .filter(Boolean)
                .join(" ")
                .toLowerCase();

            return searchableText.includes(term);
        });
    }

};


