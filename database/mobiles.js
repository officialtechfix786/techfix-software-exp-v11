/*
 * Search helper
 */

window.searchMobiles = function (query) {

    const search = String(query || "")
        .trim()
        .toLowerCase();

    if (!search) {
        return mobilesDatabase;
    }

    return mobilesDatabase.filter(function (mobile) {

        const searchableText = [
            mobile.id,
            mobile.brand,
            mobile.model,
            mobile.androidVersion,
            mobile.chipset,
            mobile.bootType,
            mobile.frp,
            mobile.firmware,
            mobile.flash,
            mobile.imeiRepair,
            mobile.networkRepair,
            mobile.unlock,
            mobile.drivers
        ]
            .join(" ")
            .toLowerCase();

        // Let technicians search shorthand such as "Samsung A15" even when
        // the full stored model name is "Samsung Galaxy A15".
        return search
            .split(/\s+/)
            .every(function (term) {
                return searchableText.includes(term);
            });
    });
};


