/*
 * Search helper
 */

window.searchMobiles = function (query) {

    const search =
        String(query || "")
            .trim()
            .toLowerCase();

    if (!search) {
        return mobilesDatabase;
    }

    return mobilesDatabase.filter((mobile) => {

        const searchableText = [

            mobile.brand,
            mobile.model,
            mobile.id,
            mobile.androidVersion,
            mobile.chipset,
            mobile.bootType,
            mobile.frp,
            mobile.firmware,
            mobile.flash,
            mobile.imeiRepair,
            mobile.networkRepair,
            mobile.unlock,
            mobile.drivers

        ]
            .join(" ")
            .toLowerCase();

        return searchableText.includes(search);

    });

};